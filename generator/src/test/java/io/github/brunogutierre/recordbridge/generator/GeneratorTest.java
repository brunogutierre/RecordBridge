package io.github.brunogutierre.recordbridge.generator;

import static org.assertj.core.api.Assertions.assertThat;

import io.github.brunogutierre.recordbridge.generator.fixture.GreetingController;
import io.github.brunogutierre.recordbridge.reader.UnmarkedNullness;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class GeneratorTest {

  private static final String FIXTURES = "io.github.brunogutierre.recordbridge.generator.fixture";

  @TempDir Path output;

  private static Path testClasses() throws Exception {
    return Path.of(
        GreetingController.class.getProtectionDomain().getCodeSource().getLocation().toURI());
  }

  private GeneratorResult generate(List<String> packages) throws Exception {
    var config = new GeneratorConfig(packages, output, UnmarkedNullness.NON_NULL);
    return Generator.generate(config, List.of(testClasses()), getClass().getClassLoader());
  }

  @Test
  void writesTheApiLayerForTheControllersInThePackages() throws Exception {
    GeneratorResult result = generate(List.of(FIXTURES));

    assertThat(result.controllers()).isEqualTo(2);
    assertThat(result.files())
        .containsExactly(
            "models.ts", "api-config.ts", "greeting.api.ts", "other.api.ts", "index.ts");
    assertThat(result.skippedClasses()).isEmpty();
    assertThat(output.resolve("greeting.api.ts"))
        .content()
        .contains("greet(name: string): Observable<Greeting>");
    assertThat(output.resolve("models.ts")).content().contains("export interface Greeting {");
  }

  @Test
  void readsOnlyTheBasePackages() throws Exception {
    GeneratorResult result = generate(List.of(FIXTURES + ".other"));

    assertThat(result.files()).contains("other.api.ts").doesNotContain("greeting.api.ts");
  }

  @Test
  void replacesItsOwnFilesButKeepsHandWrittenOnes() throws Exception {
    Files.writeString(
        output.resolve("stale.api.ts"),
        "// Generated by RecordBridge from the Spring Boot API. Do not edit.\n");
    Files.writeString(output.resolve("mine.ts"), "export const mine = 1;\n");
    Files.writeString(output.resolve("notes.md"), "# notes\n");

    generate(List.of(FIXTURES));

    assertThat(output.resolve("stale.api.ts")).doesNotExist();
    assertThat(output.resolve("mine.ts")).exists();
    assertThat(output.resolve("notes.md")).exists();
  }

  @Test
  void scannerSkipsAnonymousClassesAndPackageInfo() throws Exception {
    assertThat(ClassScanner.classNames(testClasses(), List.of(FIXTURES)))
        .contains(FIXTURES + ".GreetingController", FIXTURES + ".GreetingController$Greeting")
        .noneMatch(name -> name.contains("$1"))
        .noneMatch(name -> name.endsWith("package-info"));
    assertThat(ClassScanner.classNames(output.resolve("missing"), List.of())).isEmpty();
  }
}
