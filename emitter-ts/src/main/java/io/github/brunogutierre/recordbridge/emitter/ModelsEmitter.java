package io.github.brunogutierre.recordbridge.emitter;

import io.github.brunogutierre.recordbridge.model.ApiModel;
import io.github.brunogutierre.recordbridge.model.Property;
import io.github.brunogutierre.recordbridge.model.TypeDecl;
import java.util.Comparator;
import java.util.stream.Collectors;

/**
 * Writes the type declarations of a model as one TypeScript module.
 *
 * <ul>
 *   <li>Objects become interfaces; union tags become string literal properties.
 *   <li>Enums become a string literal union plus a {@code const} array of their values, so they are
 *       usable at runtime (in a select, for instance) without TypeScript {@code enum}s.
 *   <li>Unions become type aliases of their variants.
 * </ul>
 *
 * <p>Declarations are sorted by name, so the output only changes when the API does.
 */
public final class ModelsEmitter {

  /** The first line of every generated file. */
  public static final String HEADER =
      "// Generated by RecordBridge from the Spring Boot API. Do not edit.\n";

  /** Renders the {@code models.ts} module. */
  public String emit(ApiModel model) {
    var out = new StringBuilder(HEADER);
    model.types().stream()
        .sorted(Comparator.comparing(TypeDecl::name))
        .forEach(type -> out.append('\n').append(declaration(type)));
    if (!model.errors().isEmpty()) {
      out.append("\n/** Any body an error response of this API may carry. */\n")
          .append("export type ApiError = ")
          .append(model.errors().stream().map(Ts::type).collect(Collectors.joining(" | ")))
          .append(";\n");
    }
    return out.toString();
  }

  private static String declaration(TypeDecl type) {
    if (type instanceof TypeDecl.ObjectType object) {
      return object(object);
    }
    if (type instanceof TypeDecl.EnumType enumType) {
      return enumeration(enumType);
    }
    return union((TypeDecl.UnionType) type);
  }

  private static String object(TypeDecl.ObjectType object) {
    var out = new StringBuilder();
    out.append("export interface ")
        .append(object.name())
        .append(Ts.typeParameters(object.typeParameters()))
        .append(" {\n");
    for (TypeDecl.Tag tag : object.tags()) {
      out.append("  ")
          .append(Ts.key(tag.property()))
          .append(": ")
          .append(Ts.string(tag.value()))
          .append(";\n");
    }
    for (Property property : object.properties()) {
      out.append("  ")
          .append(Ts.key(property.name()))
          .append(property.optional() ? "?: " : ": ")
          .append(Ts.type(property.type()))
          .append(";\n");
    }
    return out.append("}\n").toString();
  }

  private static String enumeration(TypeDecl.EnumType enumType) {
    String values = enumType.constants().stream().map(Ts::string).collect(Collectors.joining(", "));
    String constant = enumType.name() + "Values";
    return "export const "
        + constant
        + " = ["
        + values
        + "] as const;\n"
        + "export type "
        + enumType.name()
        + " = (typeof "
        + constant
        + ")[number];\n";
  }

  private static String union(TypeDecl.UnionType union) {
    String variants =
        union.variants().stream().map(v -> Ts.type(v.type())).collect(Collectors.joining(" | "));
    return "export type "
        + union.name()
        + Ts.typeParameters(union.typeParameters())
        + " = "
        + variants
        + ";\n";
  }
}
